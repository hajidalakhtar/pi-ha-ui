/**
 * Colorize the ASCII-art logo in Maxwell cat color for a given frame index.
 */
function logoLines(theme: Theme, frameIndex: number): string[] {
	const mode = theme.getColorMode();
	const catColor = (text: string) => `${foregroundAnsi(CAT_COLOR, mode)}${text}${RESET}`;
	const frame = MAXWELL_FRAMES[frameIndex % MAXWELL_FRAMES.length];
	return frame.map(catColor);
}

/** Widest row of the Maxwell art across all frames; the left column is padded to it. */
const PORTRAIT_WIDTH = Math.max(...MAXWELL_FRAMES.flat().map((line) => visibleWidth(line)));
/** Width of the " │ " gap between the portrait column and the info column. */
const COLUMN_GAP = 3;
/** Below this terminal width the portrait is hidden and the info stacks in one column. */
const PORTRAIT_MIN_WIDTH = PORTRAIT_WIDTH + COLUMN_GAP + 36;

type HeaderDetails = {
	sessionId: string;
	model: string;
	provider: string;
	thinking: string;
};

type HeaderWorkspace = {
	name: string;
	path: string;
};

/** Workspace paths come from disk, so strip terminal control sequences. */
function cleanText(text: string): string {
	return stripTerminalSequences(text)
		.replace(/[\x00-\x1f\x7f-\x9f]/g, " ")
		.replace(/\s+/g, " ")
		.trim();
}

/** The workspace label, derived from the session cwd. */
function describeWorkspace(cwd: string): HeaderWorkspace {
	const directory = resolve(cwd);
	const home = homedir();
	const shortPath =
		directory === home || directory.startsWith(home + sep)
			? `~${directory.slice(home.length)}`
			: directory;
	return {
		name: cleanText(basename(directory) || directory),
		path: cleanText(shortPath),
	};
}

/**
 * Footer under the info block: a full-width rule and the slogan, both bold red.
 * It spans the whole header (below the portrait too), so it is built outside the split.
 */
function buildSloganLines(theme: Theme, width: number): string[] {
	const red = (text: string) => theme.style(text, { fg: SLOGAN_COLOR, bold: true });
	return [red(RULE_CHAR.repeat(Math.max(1, width))), red(SLOGAN)];
}

/** Right-hand column: Pi version, session metadata, and the workspace. */
function buildInfoLines(
	theme: Theme,
	details: HeaderDetails,
	workspace: HeaderWorkspace,
	now: Date,
): string[] {
	const label = (text: string) => theme.fg("dim", text);
	const value = (text: string) => theme.fg("accent", cleanText(text));

	return [
		theme.bold(value("Pi")) +
			label(` v${VERSION}`) +
			label(" · ") +
			theme.bold(value("Ha-UI")) +
			label(` v${HA_UI_VERSION}`),
		`${label("Session:")} ${value(details.sessionId)}`,
		`${label("Model:")} ${value(details.model)}`,
		`${label("Provider:")} ${value(details.provider)}`,
		`${label("Thinking:")} ${value(details.thinking)}`,
		`${label("Today:")} ${value(now.toLocaleString())}`,
		"",
		`${label("Workspace:")} ${value(workspace.name)}`,
		theme.fg("text", cleanText(workspace.path)),
	];
}

function createHaUiHeader(
	tui: TUI,
	theme: Theme,
	getDetails: () => HeaderDetails,
	workspace: HeaderWorkspace,
	animate = true,
) {
	/**
	 * The spinner runs on a finite budget: after ANIMATION_LOOPS full rotations the loop
	 * stops re-arming itself and the header never writes to the terminal again — in regular
	 * mode any write snaps the viewport back to the bottom, so going quiet for good is what
	 * keeps scroll-up working once the startup animation is over.
	 */
	const spinning = animate;
	let frameIndex = 0;
	let completedLoops = 0;
	let paused = false;
	let portraitVisible = false;
	let disposed = false;
	let timer: ReturnType<typeof setTimeout> | undefined;

	const stopTimer = () => {
		if (timer !== undefined) clearTimeout(timer);
		timer = undefined;
	};

	/**
	 * Self-rescheduling timeout chain instead of a setInterval: exactly one pending timer, a
	 * `unref`ed one so it never holds the process open, and the chain re-arms itself after
	 * every frame until the loop budget is spent.
	 */
	const schedule = () => {
		if (!spinning || paused || disposed || !portraitVisible) return;
		if (completedLoops >= ANIMATION_LOOPS || timer !== undefined) return;
		timer = setTimeout(() => {
			timer = undefined;
			if (disposed) return;
			frameIndex = (frameIndex + 1) % MAXWELL_FRAMES.length;
			if (frameIndex === 0) completedLoops++;
			tui.requestRender();
			schedule();
		}, FRAME_DELAY_MS);
		timer.unref();
	};

	return {
		render(width: number): string[] {
			portraitVisible = width >= PORTRAIT_MIN_WIDTH;
			if (portraitVisible) {
				schedule();
			} else {
				stopTimer();
				frameIndex = 0;
			}

			const art = logoLines(theme, frameIndex);
			const split = portraitVisible;
			const infoLines = buildInfoLines(theme, getDetails(), workspace, new Date());
			const separator = theme.fg("dim", "│");
			const body = split
				? infoLines.map((info, index) => {
						const portrait = art[index] ?? "";
						const left = portrait + " ".repeat(Math.max(0, PORTRAIT_WIDTH - visibleWidth(portrait)));
						return `${left} ${separator} ${info}`;
					})
				: infoLines;

			// Every line must fit the terminal width or Pi aborts the render.
			return [...body, ...buildSloganLines(theme, width)].map((line) =>
				truncateToWidth(line, width),
			);
		},
		invalidate() {},
		/** End the startup animation early (e.g. the first keystroke) without tearing down the header. */
		stopAnimation() {
			paused = true;
			stopTimer();
		},
		dispose() {
			disposed = true;
			stopTimer();
		},
	};
}

/**
 * Ensure `quietStartup: "header"` is present in ~/.pi/agent/settings.json.
 * Does not overwrite if already set to "header" or true.
 */
function ensureQuietStartup(ctx: { notify: (msg: string, level?: "info" | "warning" | "error") => void }) {
	const settingsPath = join(homedir(), ".pi", "agent", "settings.json");
	if (!existsSync(settingsPath)) return;

	try {
		const raw = readFileSync(settingsPath, "utf-8");
		const parsed = JSON.parse(raw);
		if (parsed.quietStartup === "header" || parsed.quietStartup === true) {
			return;
		}

		parsed.quietStartup = "header";
		writeFileSync(settingsPath, `${JSON.stringify(parsed, null, 2)}\n`, "utf-8");
		ctx.notify("ha-ui: quietStartup set to header. Restart Pi to hide startup resources.", "info");
	} catch (err) {
		ctx.notify(`ha-ui: failed to update quietStartup: ${err}`, "warning");
	}
}

export default function (pi: ExtensionAPI) {
	let enabled = false;
	let activeHeader: ReturnType<typeof createHaUiHeader> | undefined;
	let install: ((tui: TUI, theme: Theme) => ReturnType<typeof createHaUiHeader>) | undefined;

	const disposeHeader = () => {
		activeHeader?.dispose();
		activeHeader = undefined;
	};

	/** Cut the startup spin short the moment the user engages with the prompt. */
	const stopHeaderAnimation = () => {
		activeHeader?.stopAnimation();
	};

	pi.registerFlag("header-static", {
		description: "Disable the ha-ui header animation (Maxwell stays on the first frame)",
		type: "boolean",
		default: false,
	});

	/** Rebuild the header factory for the current session. */
	const prepareInstall = (ctx: ExtensionContext) => {
		const sessionId = ctx.sessionManager.getSessionId();
		const workspace = describeWorkspace(ctx.cwd);
		const animate = pi.getFlag("header-static") !== true;
		const getDetails = (): HeaderDetails => ({
			sessionId,
			model: ctx.model?.name ?? "No model selected",
			provider: ctx.model?.provider ?? "none",
			thinking: pi.getThinkingLevel(),
		});
		install = (tui, theme) => {
			activeHeader?.dispose();
			activeHeader = createHaUiHeader(tui, theme, getDetails, workspace, animate);
			return activeHeader;
		};
	};

	pi.on("session_start", async (_event, ctx) => {
		if (ctx.mode !== "tui") return;

		ensureQuietStartup(ctx.ui);
		prepareInstall(ctx);
		enabled = true;
		ctx.ui.setHeader(install);
	});

	pi.on("session_shutdown", () => {
		disposeHeader();
	});

	pi.on("input", async () => {
		stopHeaderAnimation();
	});

	pi.on("before_agent_start", async () => {
		stopHeaderAnimation();
	});

	pi.registerCommand("ha-ui", {
		description: "Toggle custom startup header (usage: /ha-ui [on|off])",
		handler: async (args, ctx) => {
			if (ctx.mode !== "tui") {
				ctx.ui.notify("ha-ui only operates in TUI mode.", "warning");
				return;
			}

			const arg = args.trim().toLowerCase();
			if (arg === "on") enabled = true;
			else if (arg === "off") enabled = false;
			else enabled = !enabled;

			if (!enabled) {
				disposeHeader();
				ctx.ui.setHeader(undefined);
			} else {
				prepareInstall(ctx);
				ctx.ui.setHeader(install);
			}
			ctx.ui.notify(enabled ? "ha-ui header enabled." : "Built-in Pi header restored.", "info");
		},
	});
}
