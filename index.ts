/**
 * ha-ui extension for pi-coding-agent.
 *
 * 1. Hides the noisy startup blocks via the quietStartup setting:
 *    Writes "quietStartup": "header" into settings.json. That mode keeps the
 *    startup header intact (version, key hints, custom art) but suppresses the
 *    model-scope line and the loaded-resource listing. `true` would hide the header too.
 *    The setting is written to ~/.pi/agent/settings.json and takes effect on the next start.
 *
 * 2. Replaces the Pi startup header with a split layout: animated ASCII-art Maxwell the
 *    cat (from http://ascii.live/maxwell) stays on the left, and the right column shows
 *    the Pi version (next to the ha-ui version), session ID, model, provider, thinking
 *    level, date, and the workspace
 *    (mirroring pi-custom-header). Narrow terminals drop the portrait and keep the info.
 *    Maxwell spins 5 full rotations right after startup and then goes quiet for good — once
 *    the header stops writing, regular-mode scrollback stays scrollable. The first keystroke
 *    or agent run cuts the spin short, and --header-static skips it entirely.
 *
 * Commands:
 *   /ha-ui        toggle the ha-ui header on/off (off restores the built-in header)
 *   /ha-ui on     enable the ha-ui header
 *   /ha-ui off    restore the built-in header
 */

